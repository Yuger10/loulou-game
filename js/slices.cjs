/* ---------- Manifeste des slices (feature slices v51, modules ES natifs v54) ----------
   Ce que le jeu ne peut pas dire tout seul, pour les outils et les tests :
   - `layer` : la couche de la slice. De la plus haute à la plus basse :
       app > features > entities > shared
     Une slice n'importe que sa couche ou une couche inférieure.
   - l'ORDRE du tableau : les slices sont rangées de bas en haut, et une slice
     n'importe que des slices placées AVANT elle (aucun cycle). Pour prévenir
     une slice plus haute, on émet un événement (js/shared/lib/events.js).
     js/app/main.js importe les slices dans cet ordre.
   - `files` : les modules de la slice, dans l'ordre où son index.js les
     importe. L'API publique d'une slice est son index.js : les autres slices
     n'importent que lui.
   - `css` : ses feuilles de style ; leur ordre global est CSS_ORDER.
   Tout est vérifié par test/slices.test.js. index.html et sw.js en sont
   générés (npm run sync / npm run sw).

   Ce fichier n'est pas chargé par le jeu : seuls les outils et les tests le
   lisent (`require`), d'où l'extension .cjs (js/ est en modules ES). */
